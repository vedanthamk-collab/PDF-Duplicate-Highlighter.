import assert from 'node:assert/strict';
import { PDFDocument } from 'pdf-lib';
import fs from 'node:fs';
const src=fs.readFileSync('viewer.js','utf8');
assert(!src.includes('await sleepFrame()'), 'Scanning cannot depend on animation frames');
assert(src.includes("const workerCount=Math.min(2"),'Parallel OCR workers expected');
assert(src.includes("pdf.removePage(n-1)"),'Clean PDF removal expected');
const pdf=await PDFDocument.create();
for(let i=0;i<7;i++)pdf.addPage([300,400]);
const existing=await pdf.save();
const copy=await PDFDocument.load(existing);
for(const n of [6,4,2])copy.removePage(n-1);
const result=await PDFDocument.load(await copy.save());
assert.equal(result.getPageCount(),4);
console.log('Tests passed: clean PDF removes expected number of pages; scanning not animation-frame dependent.');
